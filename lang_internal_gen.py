#!/usr/bin/env python3
"""Makes include/lang_autogen.h and src/lang_internal.c (the built-in English texts) from lng_tmpl/_base.yml.

The two files are generated and kept out of the repository (see .gitignore), so a fresh copy of the repository
does not have them. Usage: lang_internal_gen.py lng_tmpl/_base.yml include/lang_autogen.h src/lang_internal.c
"""
import sys

import yaml


def c_string(text):
    out = []
    for byte in str(text).encode("utf-8"):
        ch = chr(byte)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)  # a byte of UTF-8, as an octal escape (never swallows the next character)
    return '"' + "".join(out) + '"'


def main():
    base_path, header_path, source_path = sys.argv[1:4]
    with open(base_path, encoding="utf-8") as f:
        base = yaml.safe_load(f)

    entries = base["gui_strings"]
    prefix = base["enum_label_prefix"]
    enum_name = base["enum_name"]
    count_label = base["string_count_label"]
    array_name = base["string_array_name"]
    specifiers = base.get("string_array_specifiers", "") or ""

    labels = [e["label"] for e in entries]
    if len(set(labels)) != len(labels):
        sys.exit("lang_internal_gen: a label appears twice in " + base_path)

    with open(header_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by lang_internal_gen.py from %s. Do not edit.\n" % base_path)
        f.write("#ifndef __LANG_AUTOGEN_H\n#define __LANG_AUTOGEN_H\n\n")
        f.write("enum %s {\n" % enum_name)
        for label in labels:
            f.write("    %s%s,\n" % (prefix, label))
        f.write("    %s\n};\n\n#endif\n" % count_label)

    with open(source_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by lang_internal_gen.py from %s. Do not edit.\n" % base_path)
        f.write('#include "include/lang.h"\n\n')
        f.write("%schar *%s[%s] = {\n" % (specifiers + " " if specifiers else "", array_name, count_label))
        for entry in entries:
            value = entry["string"]
            if isinstance(value, bool):  # yes / no / on / off written without quotes
                sys.exit("lang_internal_gen: %s%s must be written in quotes" % (prefix, entry["label"]))
            f.write("    %s,\n" % c_string(value))
        f.write("};\n")


if __name__ == "__main__":
    main()
